using System;

namespace lab22
{
    // Початкова ієрархія, яка порушує LSP
    class Рахунок
    {
        public decimal Баланс { get; protected set; }

        public Рахунок(decimal початковийБаланс)
        {
            Баланс = початковийБаланс;
        }

        // Базовий метод зняття коштів
        public virtual void Зняти(decimal сума)
        {
            if (сума <= Баланс)
            {
                Баланс -= сума;
                Console.WriteLine($"Знято {сума}, залишок: {Баланс}");
            }
            else
            {
                throw new InvalidOperationException("Недостатньо коштів.");
            }
        }
    }

    // Похідний клас, що порушує LSP
    class ЗбережувальнийРахунок : Рахунок
    {
        private decimal мінімальнийБаланс;

        public ЗбережувальнийРахунок(decimal початковийБаланс, decimal мінімальнийБаланс)
            : base(початковийБаланс)
        {
            this.мінімальнийБаланс = мінімальнийБаланс;
        }

        // Перевизначаємо метод, але посилюємо передумови!
        public override void Зняти(decimal сума)
        {
            if (Баланс - сума < мінімальнийБаланс)
            {
                throw new InvalidOperationException($"Неможливо зняти кошти нижче мінімального балансу {мінімальнийБаланс}.");
            }
            base.Зняти(сума);
        }
    }

    class Програма
    {
        // Клієнтський код очікує, що можна знімати будь-яку суму, якщо вона <= Баланс
        static void ОбробитиРахунок(Рахунок рахунок, decimal сума)
        {
            try
            {
                рахунок.Зняти(сума);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Помилка: {ex.Message}");
            }
        }

        static void Main(string[] args)
        {
            Console.WriteLine("=== Початкова ієрархія (порушує LSP) ===");
            Рахунок рах1 = new Рахунок(1000);
            ЗбережувальнийРахунок рах2 = new ЗбережувальнийРахунок(1000, 500);

            // Робота з базовим класом
            ОбробитиРахунок(рах1, 800); // працює нормально
            ОбробитиРахунок(рах2, 800); // кине виняток! порушує очікування клієнта

            Console.WriteLine("\n=== Альтернатива, яка дотримується LSP ===");

            // Використовуємо композицію замість наслідування
            LSPСуміснийРахунок стандартнийРахунок = new LSPСуміснийРахунок(1000);
            LSPСуміснийРахунок збережувальнийРахунок = new LSPСуміснийРахунок(1000, 500);

            ОбробитиLSPРахунок(стандартнийРахунок, 800); // працює
            ОбробитиLSPРахунок(збережувальнийРахунок, 400); // працює, дотримується правил без порушення контракту
        }

        static void ОбробитиLSPРахунок(LSPСуміснийРахунок рахунок, decimal сума)
        {
            try
            {
                рахунок.Зняти(сума);
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Помилка: {ex.Message}");
            }
        }
    }

    // Альтернатива: клас з композицією замість порушення LSP
    class LSPСуміснийРахунок
    {
        private decimal баланс;
        private decimal мінімальнийБаланс;
        private bool маєМінімальний;

        public LSPСуміснийРахунок(decimal початковийБаланс)
        {
            баланс = початковийБаланс;
            маєМінімальний = false;
        }

        public LSPСуміснийРахунок(decimal початковийБаланс, decimal мінімальнийБаланс)
        {
            баланс = початковийБаланс;
            this.мінімальнийБаланс = мінімальнийБаланс;
            маєМінімальний = true;
        }

        public decimal Баланс => баланс;

        public void Зняти(decimal сума)
        {
            if (маєМінімальний && баланс - сума < мінімальнийБаланс)
            {
                Console.WriteLine($"Неможливо зняти кошти нижче мінімального балансу {мінімальнийБаланс}. Поточний баланс: {баланс}");
            }
            else
            {
                баланс -= сума;
                Console.WriteLine($"Знято {сума}, залишок: {баланс}");
            }
        }
    }
}